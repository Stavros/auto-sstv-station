#!/usr/bin/env python3
import os, re, sys, shutil, subprocess

SDR_TYPES = {
    "1": ("RTL-SDR", "rtl={id}", "RTL-SDR (v3 / v4 / Nooelec)"),
    "2": ("Airspy", "airspy={id}", "Airspy (R2 / Mini / HF+)"),
    "3": ("HackRF", "hackrf={id}", "HackRF One"),
    "4": ("SDRplay", "soapy={id},driver=sdrplay", "SDRplay (RSP1A / RSPdx / RSPduo)"),
    "5": ("LimeSDR", "soapy={id},driver=lime", "LimeSDR (USB / Mini)"),
    "6": ("PlutoSDR", "soapy={id},driver=plutosdr", "ADALM-PlutoSDR"),
    "7": ("USRP", "uhd", "Ettus USRP (B200 / B210)"),
    "8": ("Custom", "{id}", "Custom GQRX / SoapySDR Device String"),
}

BAND_PRESETS = {
    "1": ("2m", [(144000000, 146000000)], "2m VHF (144-146 MHz)"),
    "2": ("70cm", [(435000000, 438000000)], "70cm UHF (435-438 MHz)"),
    "3": ("dual", [(144000000, 146000000), (435000000, 438000000)], "Dual-Band 2m + 70cm"),
}

def detect_sdr_devices():
    devices = []
    try:
        out = subprocess.check_output(["rtl_test", "-t"], stderr=subprocess.STDOUT, timeout=3).decode(errors="ignore")
        for line in out.splitlines():
            m = re.search(r"^\s*(\d+):\s+.*SN:\s*(\S+)", line)
            if m:
                sn = m.group(2)
                devices.append(("RTL-SDR", sn, f"rtl={sn}", f"RTL-SDR (SN: {sn})"))
    except Exception:
        pass
    try:
        out = subprocess.check_output(["SoapySDRUtil", "--find"], stderr=subprocess.STDOUT, timeout=4).decode(errors="ignore")
        blocks = out.split("Found device")
        soapy_idx = 0
        for blk in blocks[1:]:
            drv_m = re.search(r"driver\s*=\s*(\S+)", blk)
            ser_m = re.search(r"serial\s*=\s*(\S+)", blk)
            drv = drv_m.group(1) if drv_m else "soapy"
            if drv == "rtlsdr":
                continue
            ser = ser_m.group(1) if ser_m else str(soapy_idx)
            label_map = {"sdrplay": "SDRplay", "lime": "LimeSDR", "plutosdr": "PlutoSDR", "airspy": "Airspy", "hackrf": "HackRF"}
            s_type = label_map.get(drv, "Custom")
            dev_str = f"soapy={soapy_idx},driver={drv}"
            devices.append((s_type, str(soapy_idx), dev_str, f"{s_type} (driver={drv}, SN={ser})"))
            soapy_idx += 1
    except Exception:
        pass
    if not devices:
        try:
            lsusb = subprocess.check_output(["lsusb"], timeout=3).decode(errors="ignore")
            usb_signatures = [
                ("0bda:2838", "RTL-SDR", "rtl={i}"),
                ("0bda:2832", "RTL-SDR", "rtl={i}"),
                ("1d50:60a1", "Airspy", "airspy={i}"),
                ("03eb:800c", "Airspy", "airspy={i}"),
                ("1d50:6089", "HackRF", "hackrf={i}"),
                ("1df7:", "SDRplay", "soapy={i},driver=sdrplay"),
                ("1d50:6108", "LimeSDR", "soapy={i},driver=lime"),
                ("0456:b673", "PlutoSDR", "soapy={i},driver=plutosdr"),
                ("2500:", "USRP", "uhd"),
            ]
            counters = {}
            for line in lsusb.splitlines():
                for sig, s_type, tmpl in usb_signatures:
                    if sig in line.lower():
                        idx = counters.get(s_type, 0)
                        counters[s_type] = idx + 1
                        dev_str = tmpl.format(i=idx)
                        devices.append((s_type, str(idx), dev_str, f"{s_type} #{idx} ({dev_str})"))
                        break
        except Exception:
            pass
    return devices

def format_device_string(sdr_type, dev_id):
    for _, (name, tmpl, _) in SDR_TYPES.items():
        if name == sdr_type:
            return tmpl.format(id=dev_id)
    return dev_id

def write_station_files(sdrs, lat, lon, alt, min_elev, webhook, callsign='', satnogs_token='', satnogs_id=''):
    home = os.path.expanduser("~")
    cfg_path = os.path.join(home, "config.py")
    start_path = os.path.join(home, "start_sstv.sh")
    gqrx_dir = os.path.join(home, ".config", "gqrx")
    base_gqrx = os.path.join(gqrx_dir, "default.conf")
    os.makedirs(gqrx_dir, exist_ok=True)
    with open(cfg_path, "w") as f:
        f.write("# Auto-generated by setup.py (ignored by Git)\n")
        f.write(f"LAT = {repr(lat) if lat else 'None'}\n")
        f.write(f"LON = {repr(lon) if lon else 'None'}\n")
        f.write(f"ALT = {float(alt or 0)}\n")
        f.write(f"MIN_ELEVATION = {float(min_elev or 5.0)}\n")
        f.write(f"DISCORD_WEBHOOK = {repr(webhook.strip())}\n")
        f.write("SDR_CONFIGS = [\n")
        for s in sdrs:
            f.write(f"    {repr(s)},\n")
        f.write("]\n")
    for s in sdrs:
        idx = s["index"]
        conf_file = os.path.join(gqrx_dir, f"sdr_{idx}.conf")
        if os.path.exists(base_gqrx):
            shutil.copyfile(base_gqrx, conf_file)
            with open(conf_file, "r") as cf:
                txt = cf.read()
            txt = re.sub(r"crashed=true", "crashed=false", txt)
            if "remote_control=" in txt:
                txt = re.sub(r"remote_control=\w+", "remote_control=true", txt)
            else:
                txt = txt.replace("[General]", "[General]\nremote_control=true")
            if "remote_control_port=" in txt:
                txt = re.sub(r"remote_control_port=\d+", f"remote_control_port={s['port']}", txt)
            else:
                txt = txt.replace("[General]", f"[General]\nremote_control_port={s['port']}")
            if "device=" in txt:
                txt = re.sub(r'device="[^"]*"', f'device="{s["device_str"]}"', txt)
            with open(conf_file, "w") as cf:
                cf.write(txt)
    with open(start_path, "w") as sf:
        sf.write("#!/bin/bash\nsleep 10\n\n")
        for s in sdrs:
            idx = s["index"]
            port = s["port"]
            sink = s["sink"]
            rx_dir = s["rx_dir"]
            sf.write(f"# --- SDR #{idx}: {s['sdr_type']} ({s['device_str']}) | {s['label']} ---\n")
            sf.write(f'mkdir -p "{rx_dir}"\n')
            sf.write(f'if ! pactl list short sinks | grep -q "{sink}"; then\n')
            sf.write(f'    pactl load-module module-null-sink sink_name={sink} sink_properties=device.description="SSTV_Cable_{idx}"\n')
            sf.write("fi\n")
            if idx == 0:
                sf.write(f"pactl set-default-sink {sink}\n")
                sf.write(f"pactl set-default-source {sink}.monitor\n")
            sf.write(f'sed -i "s/crashed=true/crashed=false/g" "$HOME/.config/gqrx/sdr_{idx}.conf" 2>/dev/null || true\n')
            sf.write(f"PULSE_SINK={sink} gqrx -c sdr_{idx}.conf &\n")
            sf.write("for i in {1..30}; do\n")
            sf.write(f'    RESP=$(python3 -c \'import socket; s=socket.create_connection(("127.0.0.1",{port}),1); s.sendall(b"U DSP 1\\n"); print(s.recv(64).decode().strip())\' 2>/dev/null)\n')
            sf.write('    [ "$RESP" = "RPRT 0" ] && break\n    sleep 1\ndone\n')
            sf.write(f"PULSE_SOURCE={sink}.monitor qsstv &\nsleep 2\n\n")
        sf.write("gpredict &\nsleep 2\n")
        sf.write('python3 -u "$HOME/sat_tracker.py" > "$HOME/sat_tracker.log" 2>&1 &\n')
    os.chmod(start_path, 0o755)

def run_cli():
    print("\n=== Auto-SSTV Station Setup (CLI) ===\n")
    detected = detect_sdr_devices()
    if detected:
        print(f"Detected {len(detected)} SDR device(s): " + ", ".join([d[3] for d in detected]))
    default_count = max(1, len(detected))
    count = int(input(f"How many SDR receivers do you want to configure? [{default_count}]: ").strip() or default_count)
    sdrs = []
    for idx in range(count):
        print(f"\n--- Configuring SDR #{idx} ---")
        for k, (_, _, desc) in SDR_TYPES.items():
            print(f"  {k}) {desc}")
        def_type_key = "1"
        if idx < len(detected):
            for k, (nm, _, _) in SDR_TYPES.items():
                if nm == detected[idx][0]:
                    def_type_key = k
        t_choice = input(f"  SDR Hardware Type [{def_type_key}]: ").strip() or def_type_key
        sdr_type, _, _ = SDR_TYPES.get(t_choice, SDR_TYPES["1"])
        def_id = detected[idx][1] if idx < len(detected) else "0"
        prompt_lbl = "Full GQRX/SoapySDR device string" if sdr_type == "Custom" else "Device index or serial number"
        dev_id = input(f"  {prompt_lbl} [{def_id}]: ").strip() or def_id
        device_str = format_device_string(sdr_type, dev_id)
        print("  Select RX antenna band(s) for this SDR:")
        print("    1) 2m VHF (144-146 MHz)")
        print("    2) 70cm UHF (435-438 MHz)")
        print("    3) Dual-Band (2m + 70cm)")
        print("    4) Custom MHz range")
        b_choice = input("  Band Choice: ").strip() or "1"
        if b_choice in BAND_PRESETS:
            _, ranges, label = BAND_PRESETS[b_choice]
        else:
            lo = float(input("  Start frequency in MHz (e.g. 137.0): ").strip()) * 1e6
            hi = float(input("  End frequency in MHz (e.g. 138.0): ").strip()) * 1e6
            ranges = [(int(lo), int(hi))]
            label = f"Custom ({lo/1e6:.2f}-{hi/1e6:.2f} MHz)"
        sdrs.append({
            "index": idx,
            "sdr_type": sdr_type,
            "serial": dev_id,
            "device_str": device_str,
            "port": 7356 + idx,
            "sink": f"sstv_sink_{idx}",
            "rx_dir": os.path.expanduser(f"~/qsstv/rx_sstv_{idx}" if count > 1 else "~/qsstv/rx_sstv"),
            "ranges": ranges,
            "label": label,
        })
    print("\n--- Ground Station Coordinates ---")
    print("Leave blank for Automatic detection (Gpredict .qth or IP geolocation).")
    lat = input("Latitude (e.g. 40.60) [Auto]: ").strip() or None
    lon = input("Longitude (e.g. 22.90) [Auto]: ").strip() or None
    alt = input("Altitude in meters: ").strip() or "0"
    min_elev = input("Minimum horizon elevation in degrees [5.0]: ").strip() or "5.0"
    webhook = input("\nOptional Discord Webhook URL [Leave blank to skip]: ").strip()
    callsign = input("Optional Amateur Radio Callsign (e.g. SV2HZK) [Leave blank to skip]: ").strip().upper()
    satnogs_id = input("Optional SatNOGS Ground Station ID [Leave blank to skip]: ").strip()
    satnogs_token = input("Optional SatNOGS API Token [Leave blank to skip]: ").strip()
    write_station_files(sdrs, lat, lon, alt, min_elev, webhook, callsign, satnogs_token, satnogs_id)
    print("\nSaved ~/config.py, ~/.config/gqrx/sdr_*.conf, and ~/start_sstv.sh!")

def run_gui():
    import tkinter as tk
    from tkinter import ttk, messagebox
    detected = detect_sdr_devices()
    root = tk.Tk()
    root.title("Auto-SSTV Station Setup")
    root.geometry("650x550")
    root.resizable(False, False)
    pad = {"padx": 12, "pady": 6}
    tk.Label(root, text="Auto-SSTV Station - Multi-SDR Setup", font=("Sans", 13, "bold")).pack(pady=10)
    info_txt = f"Detected {len(detected)} SDR(s): " + (", ".join([d[3] for d in detected]) if detected else "None (select manually below)")
    tk.Label(root, text=info_txt, fg="#2b6cb0").pack()
    top_frame = tk.Frame(root)
    top_frame.pack(fill="x", **pad)
    tk.Label(top_frame, text="Number of Active SDR Receivers:").pack(side="left")
    sdr_count_var = tk.IntVar(value=max(1, len(detected)))
    sdr_rows_frame = tk.LabelFrame(root, text="SDR Hardware, Device/Serial & Antenna Band Configuration", padx=10, pady=8)
    sdr_rows_frame.pack(fill="x", **pad)
    row_widgets = []
    type_names = [v[0] for v in SDR_TYPES.values()]
    def rebuild_sdr_rows():
        for w in sdr_rows_frame.winfo_children():
            w.destroy()
        row_widgets.clear()
        for idx in range(sdr_count_var.get()):
            rf = tk.Frame(sdr_rows_frame)
            rf.pack(fill="x", pady=4)
            tk.Label(rf, text=f"#{idx}").pack(side="left")
            def_type = detected[idx][0] if idx < len(detected) else "RTL-SDR"
            type_var = tk.StringVar(value=def_type)
            ttk.Combobox(rf, textvariable=type_var, width=11, state="readonly", values=type_names).pack(side="left", padx=4)
            tk.Label(rf, text="ID/SN:").pack(side="left")
            def_id = detected[idx][1] if idx < len(detected) else "0"
            sn_var = tk.StringVar(value=def_id)
            tk.Entry(rf, textvariable=sn_var, width=14).pack(side="left", padx=4)
            tk.Label(rf, text="Band:").pack(side="left", padx=(6, 2))
            band_var = tk.StringVar(value="2m VHF (144-146 MHz)")
            ttk.Combobox(rf, textvariable=band_var, width=23, state="readonly", values=[
                "2m VHF (144-146 MHz)",
                "70cm UHF (435-438 MHz)",
                "Dual-Band 2m + 70cm",
            ]).pack(side="left", padx=4)
            row_widgets.append((idx, type_var, sn_var, band_var))
    tk.Spinbox(top_frame, from_=1, to=4, textvariable=sdr_count_var, width=4, command=rebuild_sdr_rows).pack(side="left", padx=8)
    rebuild_sdr_rows()
    qth_frame = tk.LabelFrame(root, text="Ground Station Coordinates (Leave Lat/Lon blank for Automatic detection)", padx=10, pady=8)
    qth_frame.pack(fill="x", **pad)
    r1 = tk.Frame(qth_frame)
    r1.pack(fill="x", pady=2)
    tk.Label(r1, text="Lat:").pack(side="left")
    lat_var = tk.StringVar()
    tk.Entry(r1, textvariable=lat_var, width=11).pack(side="left", padx=4)
    tk.Label(r1, text="Lon:").pack(side="left")
    lon_var = tk.StringVar()
    tk.Entry(r1, textvariable=lon_var, width=11).pack(side="left", padx=4)
    tk.Label(r1, text="Alt (m):").pack(side="left")
    alt_var = tk.StringVar(value="0")
    tk.Entry(r1, textvariable=alt_var, width=6).pack(side="left", padx=4)
    tk.Label(r1, text="Min Elev (deg):").pack(side="left")
    elev_var = tk.StringVar(value="5.0")
    tk.Entry(r1, textvariable=elev_var, width=5).pack(side="left", padx=4)
    wh_frame = tk.LabelFrame(root, text="Optional Discord Webhook Alerts", padx=10, pady=8)
    wh_frame.pack(fill="x", **pad)
    wh_var = tk.StringVar()
    cs_var = tk.StringVar()
    sn_tok_var = tk.StringVar()
    sn_id_var = tk.StringVar()
    tk.Entry(wh_frame, textvariable=wh_var, width=68).pack(fill="x")
    sn_frame = tk.LabelFrame(root, text="Optional SatNOGS Network & Callsign", padx=10, pady=8)
    sn_frame.pack(fill="x", **pad)
    sr1 = tk.Frame(sn_frame)
    sr1.pack(fill="x", pady=2)
    tk.Label(sr1, text="Callsign:").pack(side="left")
    tk.Entry(sr1, textvariable=cs_var, width=12).pack(side="left", padx=4)
    tk.Label(sr1, text="SatNOGS Station ID:").pack(side="left", padx=(10, 0))
    tk.Entry(sr1, textvariable=sn_id_var, width=10).pack(side="left", padx=4)
    sr2 = tk.Frame(sn_frame)
    sr2.pack(fill="x", pady=(6, 2))
    tk.Label(sr2, text="SatNOGS API Token:").pack(side="left")
    tk.Entry(sr2, textvariable=sn_tok_var, width=48, show="*").pack(side="left", padx=4, fill="x", expand=True)
    def on_save():
        band_map = {
            "2m VHF (144-146 MHz)": [(144000000, 146000000)],
            "70cm UHF (435-438 MHz)": [(435000000, 438000000)],
            "Dual-Band 2m + 70cm": [(144000000, 146000000), (435000000, 438000000)],
}
        sdrs = []
        total = len(row_widgets)
        for idx, t_v, sn_v, b_v in row_widgets:
            s_type = t_v.get()
            dev_id = sn_v.get().strip() or "0"
            label = b_v.get()
            sdrs.append({
                "index": idx,
                "sdr_type": s_type,
                "serial": dev_id,
                "device_str": format_device_string(s_type, dev_id),
                "port": 7356 + idx,
                "sink": f"sstv_sink_{idx}",
                "rx_dir": os.path.expanduser(f"~/qsstv/rx_sstv_{idx}" if total > 1 else "~/qsstv/rx_sstv"),
                "ranges": band_map[label],
                "label": label,
            })
        write_station_files(sdrs, lat_var.get().strip() or None, lon_var.get().strip() or None, alt_var.get().strip() or "0", elev_var.get().strip() or "5.0", wh_var.get(), cs_var.get(), sn_tok_var.get(), sn_id_var.get())
        messagebox.showinfo("Saved", "Station configuration saved to ~/config.py, ~/.config/gqrx/sdr_.conf, and ~/start_sstv.sh!")
        root.destroy()
    tk.Button(root, text="Save Station Configuration", command=on_save, bg="#2f855a", fg="white", font=("Sans", 10, "bold"), padx=14, pady=6).pack(pady=12)
    root.mainloop()

if __name__ == "__main__":
    use_cli = "--cli" in sys.argv or (not os.environ.get("DISPLAY") and not os.environ.get("WAYLAND_DISPLAY"))
    if use_cli:
        run_cli()
    else:
        try:
            run_gui()
        except Exception as e:
            print(f"GUI unavailable ({e}), switching to CLI mode...")
            run_cli()
